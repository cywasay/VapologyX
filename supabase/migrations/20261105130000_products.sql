-- The shop's products. Anyone can read published products; only admins can change them.
create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  position bigint generated by default as identity,
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name text not null check (char_length(name) between 1 and 120),
  category text not null check (category in ('device', 'disposable', 'bottle', 'coil')),
  type text not null default '',
  price integer not null check (price >= 0),
  description text not null default '',
  specs jsonb not null default '[]'::jsonb check (jsonb_typeof(specs) = 'array'),
  fits uuid[] not null default '{}',
  variants jsonb not null default '[]'::jsonb check (jsonb_typeof(variants) = 'array'),
  image_url text,
  color text not null default '#e8f78b',
  badge text,
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists products_set_updated_at on public.products;
create trigger products_set_updated_at
before update on public.products
for each row execute function public.set_updated_at();

-- Row Level Security is what actually protects the table. Grants only open the door.
alter table public.products enable row level security;

revoke all on table public.products from anon, authenticated;
grant select on table public.products to anon;
grant select, insert, update, delete on table public.products to authenticated;
grant select, insert, update, delete on table public.products to service_role;

drop policy if exists "Anyone can read published products" on public.products;
create policy "Anyone can read published products"
on public.products for select to anon, authenticated
using (
  is_published
  or (select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
);

drop policy if exists "Admins can add products" on public.products;
create policy "Admins can add products"
on public.products for insert to authenticated
with check ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins can change products" on public.products;
create policy "Admins can change products"
on public.products for update to authenticated
using ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
with check ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins can delete products" on public.products;
create policy "Admins can delete products"
on public.products for delete to authenticated
using ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

